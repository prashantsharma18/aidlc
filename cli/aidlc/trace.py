"""Traceability from framework elements to guide sections, plus generated docs."""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from .paths import framework_root
from .policy import PolicyError, load_yaml
from .templates import TemplateError, parse_front_matter

CHAPTERS = {
    1: "The AI-native lifecycle, end to end", 2: "Context engineering", 3: "The agent harness",
    4: "Understanding a codebase before you change it", 5: "Intent to specification",
    6: "Architecture, boundaries and contracts", 7: "Planning and task design",
    8: "Building with an agent", 9: "Testing AI-written code",
    10: "Evaluating agents and AI workflows", 11: "Review, approval and release",
    12: "Operate, measure and improve", 13: "Security and guardrails",
    14: "Changes that span repositories", 15: "Modernising legacy systems",
    16: "Your workflow: individual, team and organisation",
}
GUIDE_RE = re.compile(r"^(1[0-6]|[1-9])(\.\d+)?( (step \d+|[A-D]\d?))?$")
LINK_RE = re.compile(r"\]\(([^)\s]+)\)")
FENCE_RE = re.compile(r"^(```|~~~).*?^\1", re.S | re.M)
INLINE_CODE_RE = re.compile(r"`[^`\n]*`")
HEADER = "<!-- Generated by aidlc trace. Do not edit: run `bin/aidlc trace`. -->\n"
SKIP_NAMES = {"README.md", "INSTRUCTIONS.md"}


@dataclass(frozen=True)
class Element:
    id: str
    kind: str
    path: str
    guide: list[str]


def _guide_problems(guide: object, label: str) -> list[str]:
    if not isinstance(guide, list) or not guide:
        return [f"{label}: no guide sections declared"]
    return [f"{label}: bad guide reference '{g}'" for g in guide
            if not isinstance(g, str) or not GUIDE_RE.match(g)]


def _chapter(ref: str) -> str:
    return ref.split(" ")[0].split(".")[0]


def collect(root: Path | None = None) -> tuple[list[Element], list[str]]:
    root = root or framework_root()
    core = root / "core"
    elements: list[Element] = []
    problems: list[str] = []

    for path in sorted((core / "policy").glob("*.yaml")):
        rel = str(path.relative_to(root))
        try:
            meta = load_yaml(path).get("meta", {})
        except (PolicyError, AttributeError) as exc:
            problems.append(f"{rel}: {exc}")
            continue
        problems += _guide_problems(meta.get("guide"), rel)
        elements.append(Element(meta.get("id", path.stem), "policy", rel, list(meta.get("guide") or [])))

    md_sources = [("template", sorted((core / "templates").glob("*.md")), "guide"),
                  ("context", sorted(p for p in (core / "context").rglob("*.md")
                                     if p.name not in SKIP_NAMES), "guide"),
                  ("skill", sorted((core / "skills").glob("*/SKILL.md")), "metadata.guide")]
    for kind, paths, key in md_sources:
        for path in paths:
            rel = str(path.relative_to(root))
            try:
                meta, _ = parse_front_matter(path.read_text(encoding="utf-8"), path)
            except TemplateError as exc:
                problems.append(f"{rel}: {exc}")
                continue
            guide = (meta.get("metadata") or {}).get("guide") if key == "metadata.guide" else meta.get("guide")
            problems += _guide_problems(guide, rel)
            ident = meta.get("id") or meta.get("name") or path.stem
            elements.append(Element(str(ident), kind, rel, list(guide or [])))
    return sorted(elements, key=lambda e: (e.kind, e.id)), problems


def render_traceability(elements: list[Element]) -> str:
    lines = [HEADER.rstrip("\n"), "# Traceability", "",
             "Every framework element and the guide sections it implements. The guide is",
             "the primary source (`~/demos/guide`); sections are written as chapter.section.", "",
             "## By chapter", "", "| Chapter | Title | Elements |", "|---|---|---|"]
    for n, title in CHAPTERS.items():
        ids = sorted({e.id for e in elements if any(_chapter(g) == str(n) for g in e.guide)})
        lines.append(f"| {n} | {title} | {', '.join(ids) if ids else '(none yet)'} |")
    lines += ["", "## By element", "", "| Element | Kind | File | Guide |", "|---|---|---|---|"]
    for e in elements:
        lines.append(f"| {e.id} | {e.kind} | `{e.path}` | {', '.join(e.guide)} |")
    return "\n".join(lines) + "\n"


def render_tiers_table(root: Path | None = None) -> str:
    root = root or framework_root()
    data = load_yaml(root / "core" / "policy" / "tiers.yaml")
    tiers = data["tiers"]
    rows = [("Typical change", "typical"), ("Spec", "spec"), ("Design", "design"),
            ("Plan", "plan"), ("Verification", "verification"), ("Approvals", "approvals"),
            ("Agent autonomy", "autonomy"), ("Release", "release"),
            ("Evidence pack items", "evidence_pack")]
    head = "| | " + " | ".join(f"Tier {t['id']} · {t['name']}" for t in tiers) + " |"
    lines = [HEADER.replace("aidlc trace.", "aidlc trace from core/policy/tiers.yaml.").rstrip("\n"),
             "# Risk tiers (generated)", "", data["rule"], "", head,
             "|---|" + "---|" * len(tiers)]
    for label, key in rows:
        cells = []
        for t in tiers:
            value = t[key]
            cells.append(", ".join(map(str, value)) if isinstance(value, list) else str(value))
        lines.append(f"| {label} | " + " | ".join(c or "none (notes in the PR)" for c in cells) + " |")
    return "\n".join(lines) + "\n"


def check_links(root: Path | None = None) -> list[str]:
    """Relative Markdown links must resolve. Links inside code (fenced or inline) are
    examples, not links, and are ignored."""
    root = root or framework_root()
    problems = []
    files = sorted((root / "docs").rglob("*.md")) if (root / "docs").is_dir() else []
    files += [p for p in (root / "README.md", root / "AGENTS.md") if p.is_file()]
    for path in files:
        text = INLINE_CODE_RE.sub("", FENCE_RE.sub("", path.read_text(encoding="utf-8")))
        for target in LINK_RE.findall(text):
            if target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            target_path = target.split("#", 1)[0]
            if target_path and not (path.parent / target_path).exists():
                problems.append(f"{path.relative_to(root)}: broken link {target}")
    return problems


def generated_docs(root: Path | None = None) -> dict[Path, str]:
    root = root or framework_root()
    elements, _ = collect(root)
    return {root / "docs" / "traceability.md": render_traceability(elements),
            root / "docs" / "operating-model" / "tiers-table.md": render_tiers_table(root)}
