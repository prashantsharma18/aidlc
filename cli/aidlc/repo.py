"""Repository configuration (.aidlc/config.yaml) and Procedure A scaffolding."""
from __future__ import annotations

import os
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

import yaml

from .paths import framework_root, safe_target
from .policy import load_yaml
from .templates import load_template, render

CONFIG = Path(".aidlc/config.yaml")
GENERATED_YAML = "# Generated by aidlc init-repo. Owned by this repository: edit freely.\n"


@dataclass
class RepoConfig:
    name: str
    owner: str
    profile: str
    purpose: str
    commands: dict[str, str] = field(default_factory=dict)
    check_steps: list[str] = field(default_factory=list)
    context: dict = field(default_factory=dict)


def load_config(repo: Path) -> RepoConfig:
    path = repo / CONFIG
    if not path.is_file():
        raise FileNotFoundError(f"{path} not found: run `aidlc init-repo` first")
    data = load_yaml(path)
    ctx = {"rules_file": "AGENTS.md", "map": "docs/codebase-map.md", "review_interval_days": 30}
    ctx.update(data.get("context") or {})
    return RepoConfig(data["name"], data["owner"], data["profile"], data.get("purpose", ""),
                      dict(data.get("commands") or {}), list(data.get("check_steps") or []), ctx)


def _write(repo: Path, rel: str, text: str, report: list[tuple[str, str]]) -> None:
    if os.path.lexists(repo / rel):          # lexists: a dangling symlink also counts
        report.append((rel, "skipped (exists)"))
        return
    try:
        path = safe_target(repo, rel)
    except ValueError as exc:
        report.append((rel, f"refused ({exc})"))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    report.append((rel, "created"))


def init_repo(repo: Path, name: str, owner: str, profile: str, purpose: str,
              today: date) -> list[tuple[str, str]]:
    profiles = load_yaml(framework_root() / "core" / "context" / "profiles.yaml")
    if profile not in profiles:
        raise ValueError(f"unknown profile '{profile}'; choose from {', '.join(profiles)}")
    chosen = profiles[profile]
    ctx = framework_root() / "core" / "context"
    report: list[tuple[str, str]] = []

    config = {"name": name, "owner": owner, "profile": profile, "purpose": purpose,
              "commands": chosen["commands"], "check_steps": chosen["check_steps"],
              "context": {"rules_file": "AGENTS.md", "map": "docs/codebase-map.md",
                          "review_interval_days": 30},
              "openwiki": {"adopted": False}}
    _write(repo, str(CONFIG), GENERATED_YAML + yaml.safe_dump(config, sort_keys=False), report)

    agents = render(load_template("agents-md"), {"NAME": name, "PURPOSE": purpose,
                                                 "OWNER": owner, "CHECK_COMMAND": "aidlc check"})
    _write(repo, "AGENTS.md", agents, report)

    cmap = render(load_template("codebase-map"), {"NAME": name, "OWNER": owner,
                                                  "DATE": today.isoformat()})
    _write(repo, "docs/codebase-map.md", cmap, report)

    _write(repo, ".aidlc/rules/README.md",
           "<!-- Generated by aidlc init-repo. -->\n# Folder rules\n\n"
           "One file per area: front matter `paths:` (globs) and the rules as Markdown.\n"
           "Render with `aidlc render --tool claude-code`. Standard: "
           "core/context/standards/folder-rules.md in the framework.\n", report)
    _write(repo, ".aidlc/probe.yaml", (ctx / "probe.yaml.tmpl").read_text(encoding="utf-8"), report)
    _write(repo, ".openwikiignore",
           (ctx / "openwiki" / "openwikiignore.baseline").read_text(encoding="utf-8"), report)
    _write(repo, "plans/approved-bundles.txt",
           "# Generated by aidlc init-repo. One approved task bundle per line, appended on main:\n"
           "# <branch> <commit>:<bundle path> <approver> <YYYY-MM-DD>\n", report)
    return report
