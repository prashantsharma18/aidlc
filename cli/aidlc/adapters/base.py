"""The adapter contract: render tool-neutral core and repository sources into one tool's
configuration. Only adapters know tool file names. See docs/adapters/interface.md."""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from ..paths import safe_target

GENERATED_MARK = "<!-- Generated by aidlc"
MARKERS = (GENERATED_MARK, "# Generated by aidlc")
MANIFEST = ".aidlc/generated.json"


class AdapterNotImplemented(Exception):
    """The adapter exists as an extension point but this function is not built yet."""


@dataclass(frozen=True)
class RenderedFile:
    path: str      # relative to the repository root, POSIX separators
    content: str


class Adapter(Protocol):
    name: str
    managed_dirs: tuple[str, ...]   # directories whose generated files it owns

    def render_rules(self, repo: Path) -> list[RenderedFile]: ...

    def render_folder_rules(self, repo: Path) -> list[RenderedFile]: ...


def _is_generated(text: str) -> bool:
    """Generated files carry a marker on one of their first lines (rule files start
    with YAML front matter, so the marker follows it)."""
    return any(line.startswith(MARKERS) for line in text.splitlines()[:6])


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _load_manifest(repo: Path) -> dict[str, str]:
    """The recorded {path: sha256} map; {} when there is no manifest yet."""
    path = repo / MANIFEST
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        data = None
    files = data.get("files") if isinstance(data, dict) else None
    if not isinstance(files, dict) or not all(
            isinstance(k, str) and isinstance(v, str) for k, v in files.items()):
        raise ValueError(f"{MANIFEST} is malformed; restore it from git")
    files.pop(MANIFEST, None)
    return dict(files)


def write_rendered(repo: Path, files: list[RenderedFile], check: bool,
                   managed_dirs: tuple[str, ...] = ()) -> list[str]:
    """Write generated files, or with check=True report what is missing or stale.

    The manifest (.aidlc/generated.json) is checked first: a recorded file whose content no
    longer matches its hash was edited by a person and is never overwritten, marker or not.
    The marker only classifies files the manifest does not know. Nothing is written through
    a symlink. Manifest entries the render no longer produces are orphans: reported (check)
    or deleted (write), unless edited, in which case they are reported and kept. Marked files
    in managed_dirs whose source is gone are treated the same way."""
    try:
        manifest = _load_manifest(repo)
    except ValueError as exc:
        return [str(exc)]
    original = dict(manifest)
    problems = []
    for f in files:
        if f.path == MANIFEST:
            problems.append(f"{f.path}: reserved for the generated-file manifest")
            continue
        try:
            target = safe_target(repo, f.path)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current is not None:
            recorded = manifest.get(f.path)
            if recorded is not None:
                if _sha(current) != recorded:
                    problems.append(f"{f.path}: edited after generation; move the change to its "
                                    f"source, delete the file, then render again")
                    continue
            elif not _is_generated(current):
                problems.append(f"{f.path}: exists and was not generated by aidlc; move its content "
                                f"to AGENTS.md or .aidlc/ and delete it, then render again")
                continue
        if current != f.content:
            if check:
                problems.append(f"{f.path}: {'missing' if current is None else 'stale'} "
                                f"(run aidlc render)")
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(f.content, encoding="utf-8")
        manifest[f.path] = _sha(f.content)

    rendered = {f.path for f in files}
    for rel in sorted(set(manifest) - rendered):
        try:
            target = safe_target(repo, rel)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        if not target.is_file():
            if check:
                problems.append(f"{rel}: orphaned (no longer rendered)")
            else:
                del manifest[rel]
        elif _sha(target.read_text(encoding="utf-8")) != manifest[rel]:
            problems.append(f"{rel}: orphaned and edited after generation; delete it by hand")
        elif check:
            problems.append(f"{rel}: orphaned (no longer rendered)")
        else:
            target.unlink()
            del manifest[rel]

    for rel_dir in managed_dirs:
        try:
            directory = safe_target(repo, rel_dir)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        for path in sorted(directory.glob("*.md")) if directory.is_dir() else []:
            rel = f"{rel_dir}/{path.name}"
            if (rel in rendered or rel in original or path.is_symlink()
                    or not _is_generated(path.read_text(encoding="utf-8"))):
                continue
            if check:
                problems.append(f"{rel}: orphaned (its source was removed); run aidlc render")
            else:
                path.unlink()

    if not check and manifest != original:
        try:
            target = safe_target(repo, MANIFEST)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps({"files": dict(sorted(manifest.items()))}, indent=2) + "\n",
                              encoding="utf-8")
        except ValueError as exc:
            problems.append(str(exc))
    return problems
