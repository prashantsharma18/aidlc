"""The adapter contract: render tool-neutral core and repository sources into one tool's
configuration. Only adapters know tool file names. See docs/adapters/interface.md."""
from __future__ import annotations

import hashlib
import json
import os
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from ..paths import CI_WORKFLOW, safe_target

GENERATED_MARK = "<!-- Generated by aidlc"
MARKERS = (GENERATED_MARK, "# Generated by aidlc")
MANIFEST = ".aidlc/generated.json"


class AdapterNotImplemented(Exception):
    """The adapter exists as an extension point but this function is not built yet."""


@dataclass(frozen=True)
class RenderedFile:
    path: str      # relative to the repository root, POSIX separators
    content: str
    source: str = ""   # where to make a change instead of editing the output (shown in refusals)
    shared: bool = False   # rendered identically by every tool (the CI workflow); owned by "shared"


class Adapter(Protocol):
    name: str
    managed_dirs: tuple[str, ...]   # directories whose generated files it owns

    def render_rules(self, repo: Path) -> list[RenderedFile]: ...

    def render_folder_rules(self, repo: Path) -> list[RenderedFile]: ...

    def render_permissions(self, repo: Path) -> list[RenderedFile]: ...

    def render_hooks(self, repo: Path) -> list[RenderedFile]: ...

    def render_skills(self, repo: Path) -> list[RenderedFile]: ...

    def render_agents(self, repo: Path) -> list[RenderedFile]: ...


def render_outputs(adapter: Adapter, repo: Path) -> list[RenderedFile]:
    """Everything an adapter renders into a repository. aidlc render, doctor D1 and the trusted CI judge
    all use this list, so a new render function reaches all three at once."""
    return (adapter.render_rules(repo) + adapter.render_folder_rules(repo) + adapter.render_permissions(repo)
            + adapter.render_hooks(repo) + adapter.render_skills(repo) + adapter.render_agents(repo))


def _is_generated(text: str) -> bool:
    """Generated files carry a marker on one of their first lines (rule files start
    with YAML front matter, so the marker follows it)."""
    return any(line.startswith(MARKERS) for line in text.splitlines()[:6])


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _load_manifest(repo: Path) -> tuple[dict[str, str], dict[str, str]]:
    """The recorded {path: sha256} and {path: owner} maps; both {} when there is no manifest yet.
    An owner is an adapter name or "shared". A manifest written before owners existed came from
    Claude Code, the only tool then, so a missing map or entry reads as claude-code (the CI
    workflow as shared). Raises ValueError for a symlinked or malformed manifest, including an
    owner that is not a known adapter."""
    from . import adapter_names  # local: the adapter registry imports this module

    path = safe_target(repo, MANIFEST)
    if not path.is_file():
        return {}, {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        data = None
    files = data.get("files") if isinstance(data, dict) else None
    recorded = data.get("owners", {}) if isinstance(data, dict) else None
    known = {*adapter_names(), "shared"}
    if (not isinstance(files, dict) or not isinstance(recorded, dict)
            or not all(isinstance(k, str) and isinstance(v, str) for k, v in files.items())
            or not all(isinstance(k, str) and v in known for k, v in recorded.items())):
        raise ValueError(f"{MANIFEST} is malformed; restore it from git")
    files.pop(MANIFEST, None)
    owners = {rel: "shared" if rel == CI_WORKFLOW else "claude-code" for rel in files}
    owners.update({rel: who for rel, who in recorded.items() if rel in files})
    return dict(files), owners


def _atomic_write(target: Path, text: str) -> None:
    """Write via a temp file in the same directory and os.replace, so a crash never leaves a
    half-written file."""
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=target.parent, prefix=target.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(tmp, target)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _save_manifest(repo: Path, manifest: dict[str, str], owners: dict[str, str]) -> None:
    target = safe_target(repo, MANIFEST)
    _atomic_write(target, json.dumps({"files": dict(sorted(manifest.items())),
                                      "owners": dict(sorted(owners.items()))}, indent=2) + "\n")


def _read(rel: str, path: Path) -> tuple[str | None, str | None]:
    """(text, None) or (None, problem). A missing file reads as (None, None)."""
    if not path.is_file():
        return None, None
    try:
        return path.read_text(encoding="utf-8"), None
    except (UnicodeDecodeError, OSError) as exc:
        return None, f"{rel}: unreadable ({type(exc).__name__}); delete it or restore it from git"


def _hint(f: RenderedFile, bare: bool = False) -> str:
    if not f.source:
        return ""
    return f.source if bare else f" ({f.source})"


def write_rendered(repo: Path, files: list[RenderedFile], check: bool,
                   managed_dirs: tuple[str, ...] = (), owner: str = "claude-code") -> list[str]:
    """Write generated files, or with check=True report what is missing or stale.

    The manifest (.aidlc/generated.json) is checked first: a recorded file whose content no
    longer matches its hash was edited by a person and is never overwritten, marker or not.
    The marker only classifies files the manifest does not know. Nothing is written through
    a symlink. Manifest entries the render no longer produces are orphans: reported (check)
    or deleted (write), unless edited, in which case they are reported and kept. Marked files
    in managed_dirs whose source is gone are treated the same way.

    Each manifest entry has an owner: the adapter that rendered it, or "shared" for a file
    every tool renders identically. A render only claims, checks and cleans up its own and
    shared entries, so rendering one tool never removes or reports another tool's files, and
    two tools cannot render the same path."""
    try:
        manifest, owners = _load_manifest(repo)
    except ValueError as exc:
        return [str(exc)]
    original, original_owners = dict(manifest), dict(owners)
    problems = []
    for f in files:
        if f.path == MANIFEST:
            problems.append(f"{f.path}: reserved for the generated-file manifest")
            continue
        mine = "shared" if f.shared else owner
        if owners.get(f.path, mine) != mine:
            problems.append(f"{f.path}: generated for {owners[f.path]}; another tool cannot render "
                            f"the same path")
            continue
        try:
            target = safe_target(repo, f.path)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        current, unreadable = _read(f.path, target)
        if unreadable:
            problems.append(unreadable)
            continue
        if current is not None and current != f.content:
            recorded = manifest.get(f.path)
            if recorded is not None:
                if _sha(current) != recorded:
                    problems.append(f"{f.path}: edited after generation; move the change to its "
                                    f"source{_hint(f)}, delete the file, then render again")
                    continue
            elif not _is_generated(current):
                problems.append(f"{f.path}: exists and was not generated by aidlc; move its content "
                                f"to {_hint(f, bare=True) or 'AGENTS.md or .aidlc/'} and delete it, "
                                f"then render again")
                continue
        if current != f.content:
            if check:
                problems.append(f"{f.path}: {'missing' if current is None else 'stale'} "
                                f"(run aidlc render)")
                continue
            _atomic_write(target, f.content)
        manifest[f.path] = _sha(f.content)
        owners[f.path] = mine

    rendered = {f.path for f in files}
    for rel in sorted(set(manifest) - rendered):
        if owners.get(rel) not in (owner, "shared"):
            continue
        try:
            target = safe_target(repo, rel)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        if not target.is_file():
            if check:
                problems.append(f"{rel}: orphaned (no longer rendered)")
            else:
                del manifest[rel]
                owners.pop(rel, None)
        elif (text := _read(rel, target))[1]:
            problems.append(text[1])
        elif _sha(text[0]) != manifest[rel]:
            problems.append(f"{rel}: orphaned and edited after generation; delete it by hand")
        elif check:
            problems.append(f"{rel}: orphaned (no longer rendered)")
        else:
            target.unlink()
            del manifest[rel]
            owners.pop(rel, None)

    for rel_dir in managed_dirs:
        try:
            directory = safe_target(repo, rel_dir)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        for path in sorted(directory.glob("*.md")) if directory.is_dir() else []:
            rel = f"{rel_dir}/{path.name}"
            if rel in rendered or rel in original or path.is_symlink():
                continue
            text, unreadable = _read(rel, path)
            if unreadable:
                problems.append(unreadable)
                continue
            if not _is_generated(text):
                continue
            if check:
                problems.append(f"{rel}: orphaned (its source was removed); run aidlc render")
            else:
                path.unlink()

    if not check and (manifest != original or owners != original_owners):
        try:
            _save_manifest(repo, manifest, owners)
        except ValueError as exc:
            problems.append(str(exc))
    return problems
