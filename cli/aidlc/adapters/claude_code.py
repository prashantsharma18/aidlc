"""Claude Code adapter: CLAUDE.md imports AGENTS.md; folder rules become .claude/rules/."""
from __future__ import annotations

from pathlib import Path

from ..templates import TemplateError, parse_front_matter
from .base import RenderedFile

RULES_HEADER = ("<!-- Generated by aidlc render (claude-code). Do not edit: change AGENTS.md "
                "or .aidlc/claude.md, then run `aidlc render --tool claude-code`. -->\n")


class ClaudeCodeAdapter:
    name = "claude-code"
    managed_dirs = (".claude/rules",)

    def render_rules(self, repo: Path) -> list[RenderedFile]:
        if not (repo / "AGENTS.md").is_file():
            raise ValueError(f"{repo / 'AGENTS.md'} is missing: write the rules file first "
                             "(aidlc init-repo)")
        text = RULES_HEADER + "@AGENTS.md\n"
        extra = repo / ".aidlc" / "claude.md"
        if extra.is_symlink():
            raise ValueError(f"{extra} is a symlink; refusing to read rules through it")
        if extra.is_file():
            body = extra.read_text(encoding="utf-8").lstrip("﻿").replace("\r\n", "\n")
            text += "\n" + body.rstrip("\n") + "\n"
        return [RenderedFile("CLAUDE.md", text)]

    def render_folder_rules(self, repo: Path) -> list[RenderedFile]:
        out = []
        for src in sorted((repo / ".aidlc" / "rules").glob("*.md")):
            if src.name == "README.md":
                continue
            try:
                meta, body = parse_front_matter(src.read_text(encoding="utf-8"), src)
            except TemplateError as exc:
                raise ValueError(str(exc)) from exc
            paths = meta.get("paths")
            if not isinstance(paths, list) or not paths or not all(isinstance(p, str) for p in paths):
                raise ValueError(f"{src}: front matter needs 'paths:' as a non-empty list of globs")
            front = "---\npaths:\n" + "".join(f'  - "{p}"\n' for p in paths) + "---\n"
            note = (f"<!-- Generated by aidlc render (claude-code) from .aidlc/rules/{src.name}. "
                    "Do not edit. -->\n")
            out.append(RenderedFile(f".claude/rules/{src.name}",
                                    front + note + body.rstrip("\n") + "\n"))
        return out
