"""Claude Code adapter: CLAUDE.md imports AGENTS.md; folder rules become .claude/rules/."""
from __future__ import annotations

import importlib.util
import json
import os
import subprocess
from pathlib import Path

from ..harness import HarnessError, effective_permissions, harness_data, map_tools
from ..paths import framework_root
from ..policy import load_yaml
from ..repo import CONFIG, load_config
from ..templates import TemplateError, parse_front_matter
from .base import RenderedFile

RULES_HEADER = ("<!-- Generated by aidlc render (claude-code). Do not edit: change AGENTS.md "
                "or .aidlc/claude.md, then run `aidlc render --tool claude-code`. -->\n")

SCHEMA = "https://json.schemastore.org/claude-code-settings.json"
PRE_MATCHER = "^(Edit|Write|MultiEdit|NotebookEdit|Bash|WebFetch|WebSearch|mcp__.*)$"
POST_MATCHER = "^(Edit|Write|MultiEdit|NotebookEdit|Bash)$"
HOOK_FILES = ("guard.py", "post_check.py", "claude_shim.py")
GLOB_CHARS = "*?["
LS_FILES_TIMEOUT = 20


def _dedupe(items):
    out = []
    for item in items:
        if item not in out:
            out.append(item)
    return out


def _has_glob(text: str) -> bool:
    return any(ch in text for ch in GLOB_CHARS)


def _sandbox_path(pattern: str) -> str | None:
    """A secret path as a sandbox denyRead entry (denyRead supports globs, verified
    2026-10-19). Home globs ending in /** become the directory."""
    if pattern.startswith("~"):
        return pattern[:-3] if pattern.endswith("/**") else pattern
    if pattern.endswith("/**") and not _has_glob(pattern[:-3]):
        return f"./{pattern[:-3]}"
    return pattern if pattern.startswith("./") else f"./{pattern}"


def _guard_matcher():
    """The guard's own matcher, so the sandbox and the guard agree on what a pattern covers."""
    path = framework_root() / "core" / "hooks" / "guard.py"
    spec = importlib.util.spec_from_file_location("aidlc_render_guard", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.matches


def _tracked_files(repo: Path) -> list[str]:
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    try:
        result = subprocess.run(["git", "ls-files", "-z"], cwd=repo, env=env, capture_output=True,
                                timeout=LS_FILES_TIMEOUT)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise HarnessError(f"cannot list tracked files in {repo} ({type(exc).__name__}); "
                           "the sandbox write denies need them") from exc
    if result.returncode != 0:
        raise HarnessError(f"git ls-files failed in {repo}: "
                           f"{result.stderr.decode(errors='replace').strip()}; the sandbox write "
                           "denies need a git repository")
    return [p for p in result.stdout.decode("utf-8", errors="surrogateescape").split("\0") if p]


def _is_literal_protected(entry: str) -> bool:
    """True when a protected path maps to literal sandbox denyWrite entries; False when it is a
    glob that must be expanded to tracked files."""
    return (entry == ".git/**" or entry.startswith("~") or not _has_glob(entry)
            or (entry.endswith("/**") and not _has_glob(entry[:-3])))


def _deny_write(repo: Path, protected: list[str]) -> list[str]:
    """Sandbox denyWrite supports only literal files and directories (verified 2026-10-19), so
    glob entries are expanded to the tracked files they match."""
    out, globs = [], []
    for pattern in protected:
        if pattern == ".git/**":
            out += ["./.git/hooks", "./.git/config"]     # a full .git deny would break commits
        elif not _is_literal_protected(pattern):
            globs.append(pattern)
        elif pattern.startswith("~"):
            out.append(pattern[:-3] if pattern.endswith("/**") else pattern)
        elif pattern.endswith("/**"):
            out.append(f"./{pattern[:-3]}")
        else:
            out.append(f"./{pattern}")
    if globs:
        matches = _guard_matcher()
        tracked = _tracked_files(repo)
        for pattern in globs:
            out += [f"./{p}" for p in tracked if matches(p, [pattern], any_depth_names=True)]
    return _dedupe(out)


def _hook(phase: str) -> dict:
    return {"type": "command",
            "command": f'python3 "${{CLAUDE_PROJECT_DIR}}/.aidlc/hooks/claude_shim.py" {phase}',
            "timeout": 10, "onFailure": "block"}


class ClaudeCodeAdapter:
    name = "claude-code"
    managed_dirs = (".claude/rules", ".aidlc/hooks")

    def render_rules(self, repo: Path) -> list[RenderedFile]:
        if not (repo / "AGENTS.md").is_file():
            raise ValueError(f"{repo / 'AGENTS.md'} is missing: write the rules file first "
                             "(aidlc init-repo)")
        text = RULES_HEADER + "@AGENTS.md\n"
        extra = repo / ".aidlc" / "claude.md"
        if extra.is_symlink():
            raise ValueError(f"{extra} is a symlink; refusing to read rules through it")
        if extra.is_file():
            body = extra.read_text(encoding="utf-8").lstrip("﻿").replace("\r\n", "\n")
            text += "\n" + body.rstrip("\n") + "\n"
        return [RenderedFile("CLAUDE.md", text)]

    def render_folder_rules(self, repo: Path) -> list[RenderedFile]:
        out = []
        for src in sorted((repo / ".aidlc" / "rules").glob("*.md")):
            if src.name == "README.md":
                continue
            try:
                meta, body = parse_front_matter(src.read_text(encoding="utf-8"), src)
            except TemplateError as exc:
                raise ValueError(str(exc)) from exc
            paths = meta.get("paths")
            if not isinstance(paths, list) or not paths or not all(isinstance(p, str) for p in paths):
                raise ValueError(f"{src}: front matter needs 'paths:' as a non-empty list of globs")
            front = "---\npaths:\n" + "".join(f'  - "{p}"\n' for p in paths) + "---\n"
            note = (f"<!-- Generated by aidlc render (claude-code) from .aidlc/rules/{src.name}. "
                    "Do not edit. -->\n")
            out.append(RenderedFile(f".claude/rules/{src.name}",
                                    front + note + body.rstrip("\n") + "\n"))
        return out

    def render_permissions(self, repo: Path) -> list[RenderedFile]:
        if not (repo / CONFIG).is_file():
            return []                      # the framework repository itself: rules file only
        eff = effective_permissions(repo)
        cfg = load_config(repo)
        profile = load_yaml(framework_root() / "core" / "context" / "profiles.yaml")[cfg.profile]
        tools = cfg.tool_names
        allow = ["Read" if p == "**" else f"Read(./{p})" for p in eff["allow"]["read"]]
        allow += [f"Edit(./{p})" for p in eff["allow"]["edit"]]
        allow += [f"Bash({s})" for s in eff["allow"]["shell"]]
        allow += map_tools(eff["allow"]["tools"], tools)[0]
        ask = [f"Edit({p})" for p in eff["ask"]["edit"]] + [f"Bash({s})" for s in eff["ask"]["shell"]]
        ask += map_tools(eff["ask"]["tools"], tools)[0]
        deny = [f"Read({p})" for p in _dedupe(eff["secret_paths"] + eff["deny"]["read"])]
        deny += [f"Edit({p})" for p in eff["deny"]["edit"]]
        deny += [f"Bash({s})" for s in eff["deny"]["shell"]]
        deny += map_tools(eff["deny"]["tools"], tools)[0]
        settings = {
            "$schema": SCHEMA,
            "permissions": {"allow": _dedupe(allow), "ask": _dedupe(ask), "deny": _dedupe(deny),
                            "disableBypassPermissionsMode": "disable"},
            "sandbox": {
                "enabled": True, "failIfUnavailable": True, "allowUnsandboxedCommands": False,
                "autoAllowBashIfSandboxed": True,
                "filesystem": {
                    "denyRead": _dedupe([_sandbox_path(s) for s in eff["secret_paths"]]),
                    "denyWrite": _deny_write(repo, eff["protected_paths"]),
                    "allowWrite": _dedupe(profile.get("sandbox_allow_write", [])
                                          + eff["sandbox_allow_write_add"])},
                "network": {"allowedDomains": _dedupe(profile.get("network_allow", [])
                                                      + eff["network_allow_add"])},
            },
            "hooks": {"PreToolUse": [{"matcher": PRE_MATCHER, "hooks": [_hook("pre")]}],
                      "PostToolUse": [{"matcher": POST_MATCHER, "hooks": [_hook("post")]}]},
            "autoMemoryEnabled": bool(cfg.harness.get("auto_memory", False)),
        }
        plugins = cfg.harness.get("disable_user_plugins") or []
        if plugins:
            settings["enabledPlugins"] = {p: False for p in plugins}
        return [RenderedFile(".claude/settings.json", json.dumps(settings, indent=2) + "\n")]

    def render_hooks(self, repo: Path) -> list[RenderedFile]:
        if not (repo / CONFIG).is_file():
            return []
        out = []
        src = framework_root() / "core" / "hooks"
        for name in HOOK_FILES:
            lines = (src / name).read_text(encoding="utf-8").splitlines(keepends=True)
            note = f"# Generated by aidlc render (claude-code) from core/hooks/{name}. Do not edit.\n"
            out.append(RenderedFile(f".aidlc/hooks/{name}", lines[0] + note + "".join(lines[1:])))
        out.append(RenderedFile(".aidlc/hooks/harness.json",
                                json.dumps(harness_data(repo), indent=2) + "\n"))
        return out
