PINNED = re.compile(r"^[^@\s]+@[0-9a-f]{40}$")


def installed(profile="node", ci=("github",), base="main"):
    repo = TempRepo({"package.json": "{}\n"})
    root = repo.__enter__()
    init_repo(root, "svc", "team", profile, "purpose", date(2026, 10, 19))
    path = root / ".aidlc/config.yaml"
    cfg = yaml.safe_load(path.read_text())
    cfg["ci"] = list(ci)
    cfg["harness"]["base_branch"] = base
    path.write_text(yaml.safe_dump(cfg, sort_keys=False))
    return repo, root


def workflow(root):
    [f] = render_ci(root)
    data = yaml.safe_load(f.content)
    data.setdefault("on", data.pop(True, None))        # PyYAML reads the key `on` as True
    return f, data


class TemplateTest(unittest.TestCase):
    def setUp(self):
        self.repo, self.root = installed()

    def tearDown(self):
        self.repo.__exit__(None, None, None)

    def test_marker_and_path(self):
        f, _ = workflow(self.root)
        self.assertEqual(f.path, OUTPUT)
        self.assertTrue(any(line.startswith("# Generated by aidlc") for line in f.content.splitlines()[:6]))

    def test_read_only_and_pull_request_only(self):
        _, data = workflow(self.root)
        self.assertEqual(data["on"], {"pull_request": {"branches": ["main"]}})
        self.assertEqual(data["permissions"], {"contents": "read"})
        for job in data["jobs"].values():
            self.assertNotIn("permissions", job)

    def test_jobs_are_the_required_checks(self):
        _, data = workflow(self.root)
        required = set(load_policy("branch-protection")["required_checks"])
        self.assertEqual(set(data["jobs"]), {"compile", "check", "scans"})
        self.assertTrue(set(data["jobs"]) <= required)

    def test_every_action_is_pinned_and_no_untrusted_text_in_run(self):
        f, data = workflow(self.root)
        for name, job in data["jobs"].items():
            for step in job["steps"]:
                if "uses" in step:
                    with self.subTest(job=name, uses=step["uses"]):
                        self.assertRegex(step["uses"], PINNED)
                if "run" in step:
                    self.assertNotRegex(step["run"], r"\$\{\{\s*github\.(head_ref|event\.pull_request)")

    def test_each_job_runs_aidlc_ci_for_its_group(self):
        _, data = workflow(self.root)
        for name, job in data["jobs"].items():
            runs = " ".join(step.get("run", "") for step in job["steps"])
            with self.subTest(job=name):
                self.assertIn(f"--group {name}", runs)
                self.assertIn("--trusted trusted --head pr", runs)
        scans = " ".join(step.get("run", "") for step in data["jobs"]["scans"]["steps"])
        self.assertIn("aidlc tools install conftest", scans)

    def test_profile_setup_and_base_branch(self):
        _, data = workflow(self.root)
        uses = [s.get("uses", "") for s in data["jobs"]["check"]["steps"]]
        self.assertTrue(any(u.startswith("actions/setup-node@") for u in uses))
        repo, root = installed(profile="dotnet", base="develop")
        try:
            _, data = workflow(root)
            self.assertEqual(data["on"]["pull_request"]["branches"], ["develop"])
            uses = [s.get("uses", "") for s in data["jobs"]["check"]["steps"]]
            self.assertTrue(any(u.startswith("actions/setup-dotnet@") for u in uses))
        finally:
            repo.__exit__(None, None, None)

    def test_framework_checkout_and_head_are_pinned(self):
        f, data = workflow(self.root)
        for name, job in data["jobs"].items():
            with self.subTest(job=name):
                first = job["steps"][0]
                self.assertIn("AIDLC_FRAMEWORK_REF", first["run"])
                self.assertRegex(first["run"], r"\[0-9a-f\]\{40\}")
                pr = next(s for s in job["steps"] if s.get("with", {}).get("path") == "pr")
                self.assertEqual(pr["with"]["ref"], "${{ github.event.pull_request.head.sha }}")
                runs = " ".join(step.get("run", "") for step in job["steps"])
                self.assertIn("git -C aidlc rev-parse HEAD", runs)
                self.assertIn("--sandbox auto" if name == "scans" else "--sandbox require", runs)
                self.assertIn(f'--records "$RUNNER_TEMP/ci-records-{name}"', runs)

    def test_base_branch_is_a_string(self):
        repo, root = installed(base="1.0")
        try:
            _, data = workflow(root)
            self.assertEqual(data["on"]["pull_request"]["branches"], ["1.0"])
        finally:
            repo.__exit__(None, None, None)

    def test_render_is_idempotent_and_protects_the_workflow(self):
        code, out, _ = run_cli("render", "--tool", "claude-code", str(self.root))
        self.assertEqual(code, 0, out)
        settings = json.loads((self.root / ".claude/settings.json").read_text())
        self.assertIn("./.github", settings["sandbox"]["filesystem"]["denyWrite"])
        code, out, _ = run_cli("render", "--tool", "claude-code", "--check", str(self.root))
        self.assertEqual(code, 0, out)

    def test_render_writes_it_and_doctor_sees_a_hand_edit(self):
        code, out, _ = run_cli("render", "--tool", "claude-code", str(self.root))
        self.assertEqual(code, 0, out)
        path = self.root / OUTPUT
        self.assertTrue(path.is_file())
        code, out, _ = run_cli("render", "--tool", "claude-code", "--check", str(self.root))
        self.assertEqual(code, 0, out)
        path.write_text(path.read_text().replace("contents: read", "contents: write"))
        self.assertTrue(any(OUTPUT in str(f) for f in check_d1(self.root)))

    def test_no_ci_configured_renders_nothing(self):
        repo, root = installed(ci=())
        try:
            self.assertEqual(render_ci(root), [])
        finally:
            repo.__exit__(None, None, None)

    def test_unknown_ci_value_rejected(self):
        repo, root = installed(ci=("gitlab",))
        try:
            with self.assertRaises(ValueError):
                load_config(root)
        finally:
            repo.__exit__(None, None, None)

    def test_a_fork_pull_request_never_borrows_a_branch_name(self):          # final review minor 9
        expression = ("${{ github.event.pull_request.head.repo.full_name == github.repository && github.head_ref "
                      "|| format('fork-pr-{0}', github.event.pull_request.number) }}")
        _, data = workflow(self.root)
        for name, job in data["jobs"].items():
            [step] = [s for s in job["steps"] if "aidlc ci " in s.get("run", "")]
            with self.subTest(job=name):
                self.assertEqual(step["env"]["BRANCH"], expression)
                self.assertNotIn("HEAD_REF", step["env"])
                self.assertIn('--branch "$BRANCH"', step["run"])
                self.assertNotIn("${{", step["run"])

    @unittest.skipUnless(which_tool("conftest"), "conftest is not installed: run `aidlc tools install conftest`")
    def test_rendered_workflow_passes_the_rego_pack(self):
        run_cli("render", "--tool", "claude-code", str(self.root))
        fails = [str(f) for f in run_conftest(self.root) if f.level == "FAIL" and OUTPUT in f.file]
        self.assertEqual(fails, [])


    @unittest.skipUnless(which_tool("conftest"), "conftest is not installed: run `aidlc tools install conftest`")
    def test_the_rego_pack_really_evaluates_the_workflow(self):
        run_cli("render", "--tool", "claude-code", str(self.root))
        path = self.root / OUTPUT
        path.write_text(path.read_text().replace("permissions:\n  contents: read\n", "permissions: write-all\n"))
        fails = [f for f in run_conftest(self.root) if f.level == "FAIL" and OUTPUT in f.file]
        self.assertTrue(fails)


class JudgeGeneratedTest(unittest.TestCase):
    """The CI judge re-renders the workflow from the head and compares it byte for byte."""

    def setUp(self):
        self.repo, self.root = installed()
        code, out, _ = run_cli("render", "--tool", "claude-code", str(self.root))
        self.assertEqual(code, 0, out)

    def tearDown(self):
        self.repo.__exit__(None, None, None)

    def test_a_correctly_rendered_head_passes(self):
        from aidlc.checks.conftest_check import judge_generated
        self.assertEqual([str(f) for f in judge_generated(self.root, self.root)], [])

    def test_a_hand_edited_workflow_fails(self):
        from aidlc.checks.conftest_check import judge_generated
        path = self.root / OUTPUT
        lines = path.read_text().splitlines(keepends=True)
        path.write_text("".join(line for line in lines if "upload-artifact" not in line))
        findings = judge_generated(self.root, self.root)
        self.assertTrue(any(f.level == "FAIL" and OUTPUT in f.file for f in findings), findings)

    def test_a_missing_workflow_fails(self):
        from aidlc.checks.conftest_check import judge_generated
        (self.root / OUTPUT).unlink()
        findings = judge_generated(self.root, self.root)
        self.assertTrue(any(f.level == "FAIL" for f in findings), findings)

    def test_adding_ci_after_first_render_keeps_settings_current(self):
        repo, root = installed(ci=())
        try:
            code, out, _ = run_cli("render", "--tool", "claude-code", str(root))
            self.assertEqual(code, 0, out)
            path = root / ".aidlc/config.yaml"
            cfg = yaml.safe_load(path.read_text())
            cfg["ci"] = ["github"]
            path.write_text(yaml.safe_dump(cfg, sort_keys=False))
            code, out, _ = run_cli("render", "--tool", "claude-code", "--check", str(root))
            self.assertEqual(code, 1, out)                       # the workflow is new, so stale
            code, out, _ = run_cli("render", "--tool", "claude-code", str(root))
            self.assertEqual(code, 0, out)
            code, out, _ = run_cli("render", "--tool", "claude-code", "--check", str(root))
            self.assertEqual(code, 0, out)
            from aidlc.checks.conftest_check import judge_generated
            self.assertEqual([str(f) for f in judge_generated(root, root)], [])
        finally:
            repo.__exit__(None, None, None)


class FixRoundOneTest(unittest.TestCase):
    def setUp(self):
        self.repo, self.root = installed()

    def tearDown(self):
        self.repo.__exit__(None, None, None)

    def test_header_states_the_trust_boundary(self):
        f, _ = workflow(self.root)
        header = "\n".join(line for line in f.content.splitlines() if line.startswith("#"))
        self.assertIn("CODEOWNERS", header)
        self.assertIn("/.github/", header)
        self.assertIn("/.aidlc/", header)
        self.assertIn("code-owner review", header)
        self.assertIn("required-workflow", header)
        self.assertNotIn("from the protected base", header)

    def test_branch_protection_requires_code_owned_workflow_paths(self):
        policy = load_policy("branch-protection")
        # Final review minor 10 adds the trusted evidence files that CI reads from the base.
        self.assertEqual(policy["code_owned_paths"], ["/.github/", "/.aidlc/", "/plans/approved-bundles.txt",
                                                      "/test/allowed-skips.txt",
                                                      "/test/protected-exceptions.txt"])

    def test_policy_validate_requires_every_evidence_path(self):                 # final review minor 10
        import aidlc.policy as policy
        data = load_policy("branch-protection")
        schema = policy._schema(policy.framework_root(), "branch-protection")
        self.assertFalse(policy._errors(schema, data, "bp"))
        for path in data["code_owned_paths"]:
            with self.subTest(path=path):
                self.assertTrue(policy._errors(schema, dict(data, code_owned_paths=[
                    p for p in data["code_owned_paths"] if p != path]), "bp"))

    def test_header_names_the_evidence_paths(self):                              # final review minor 10
        f, _ = workflow(self.root)
        header = "\n".join(line for line in f.content.splitlines() if line.startswith("#"))
        for path in ("/plans/approved-bundles.txt", "/test/allowed-skips.txt",
                     "/test/protected-exceptions.txt"):
            self.assertIn(path, header)

    def test_policy_validate_rejects_a_bad_code_owned_paths(self):
        import aidlc.policy as policy
        data = load_policy("branch-protection")
        data = dict(data, code_owned_paths=[])
        schema = policy._schema(policy.framework_root(), "branch-protection")
        self.assertTrue(policy._errors(schema, data, "bp"))

    def test_policy_test_target_runs_this_file(self):
        from aidlc.paths import framework_root
        text = (framework_root() / "Makefile").read_text()
        self.assertIn("tests.unit.test_ci_templates", text)

    def test_trusted_checkout_is_the_base_sha(self):
        _, data = workflow(self.root)
        for name, job in data["jobs"].items():
            with self.subTest(job=name):
                trusted = next(s for s in job["steps"] if s.get("with", {}).get("path") == "trusted")
                self.assertEqual(trusted["with"]["ref"], "${{ github.event.pull_request.base.sha }}")

    def test_setup_node_does_not_cache(self):
        _, data = workflow(self.root)
        step = next(s for s in data["jobs"]["check"]["steps"] if s.get("uses", "").startswith("actions/setup-node@"))
        self.assertIs(step["with"]["package-manager-cache"], False)

    def test_doctor_needs_the_toolchain_file(self):
        from aidlc.checks.doctor import check_d14
        for profile, name in (("node", ".nvmrc"), ("dotnet", "global.json")):
            repo, root = installed(profile=profile)
            try:
                with self.subTest(profile=profile):
                    found = check_d14(root)
                    self.assertEqual(
                        [f.message for f in found],
                        [f"ci: [github] needs {name} at the repository root for the {profile} toolchain"])
                    self.assertTrue(all(f.level == "FAIL" for f in found))
                    (root / name).write_text("x\n")
                    self.assertEqual(check_d14(root), [])
            finally:
                repo.__exit__(None, None, None)

    def test_doctor_needs_nothing_without_ci_or_for_generic(self):
        from aidlc.checks.doctor import check_d14
        repo, root = installed(ci=())
        try:
            self.assertEqual(check_d14(root), [])
        finally:
            repo.__exit__(None, None, None)
        repo, root = installed(profile="generic")
        try:
            self.assertEqual(check_d14(root), [])
        finally:
            repo.__exit__(None, None, None)

    def test_doctor_survives_an_unknown_ci_value(self):
        from aidlc.checks.doctor import run_doctor
        repo, root = installed(ci=("gitlab",))
        try:
            findings = run_doctor(root, which=lambda _: None)
            self.assertTrue(any(f.level == "FAIL" for f in findings))
        finally:
            repo.__exit__(None, None, None)

    def test_trace_lists_ci_github(self):
        from aidlc.trace import collect
        elements, problems = collect()
        self.assertEqual(problems, [])
        self.assertIn("ci-github", {e.id for e in elements})

    def test_render_ignores_meta_and_rejects_bad_setup(self):
        import shutil
        import tempfile
        from pathlib import Path
        from unittest import mock
        from aidlc.paths import framework_root
        [f] = render_ci(self.root)
        self.assertNotIn("review_by", f.content)
        for body in ("meta: {id: x}\nnode: 5\ngeneric: ''\n", "meta: {id: x}\ngeneric: ''\n"):
            with tempfile.TemporaryDirectory() as tmp:
                fw = Path(tmp)
                shutil.copytree(framework_root() / "core" / "ci", fw / "core" / "ci")
                (fw / "core/ci/github/setup.yaml").write_text(body)
                with mock.patch("aidlc.ci_templates.framework_root", return_value=fw):
                    with self.assertRaises(ValueError):
                        render_ci(self.root)

    def test_judge_renders_when_only_the_trusted_config_lists_github(self):
        from aidlc.checks.conftest_check import judge_generated
        run_cli("render", "--tool", "claude-code", str(self.root))
        trusted = self.root
        repo, head = installed(ci=())
        try:
            run_cli("render", "--tool", "claude-code", str(head))
            findings = judge_generated(head, trusted)
            self.assertTrue(any(f.level == "FAIL" and OUTPUT in str(f.file) + f.message for f in findings), findings)
        finally:
            repo.__exit__(None, None, None)
