import unittest
from pathlib import Path

from aidlc.adapters import get_adapter
from aidlc.adapters.base import AdapterNotImplemented, write_rendered
from tests.helpers import TempRepo, run_cli

FIX = Path(__file__).resolve().parents[1] / "fixtures" / "render" / "claude-code"
SOURCE = {
    "AGENTS.md": "# x: agent guide\n",
    ".aidlc/claude.md": "## Claude Code only\n- Use plan mode for planning steps.\n",
    ".aidlc/rules/migrations.md": "---\r\npaths: [\"db/migrations/**\"]\r\n---\r\n"
                                  "Never edit an existing migration; add a new one.\r\n",
    ".aidlc/rules/README.md": "# ignored\n",
}


class AdapterTest(unittest.TestCase):
    def test_claude_output_matches_golden(self):
        with TempRepo(SOURCE) as root:
            adapter = get_adapter("claude-code")
            files = adapter.render_rules(root) + adapter.render_folder_rules(root)
            got = {f.path: f.content for f in files}
            self.assertEqual(set(got), {"CLAUDE.md", ".claude/rules/migrations.md"})
            for rel, content in got.items():
                self.assertEqual(content, (FIX / rel).read_text(encoding="utf-8"), rel)

    def test_render_is_deterministic(self):
        with TempRepo(SOURCE) as root:
            a = get_adapter("claude-code")
            self.assertEqual(a.render_folder_rules(root), a.render_folder_rules(root))

    def test_refuses_to_overwrite_hand_written_claude_md(self):
        with TempRepo({**SOURCE, "CLAUDE.md": "# mine\n"}) as root:
            problems = write_rendered(root, get_adapter("claude-code").render_rules(root), check=False)
            self.assertTrue(any("not generated by aidlc" in p for p in problems))
            self.assertEqual((root / "CLAUDE.md").read_text(encoding="utf-8"), "# mine\n")

    def test_check_mode_reports_stale_and_missing(self):
        with TempRepo(SOURCE) as root:
            files = get_adapter("claude-code").render_rules(root)
            self.assertTrue(write_rendered(root, files, check=True))
            write_rendered(root, files, check=False)
            self.assertEqual(write_rendered(root, files, check=True), [])

    def test_rule_without_paths_is_an_error(self):
        with TempRepo({**SOURCE, ".aidlc/rules/bad.md": "---\ndescription: x\n---\nbody\n"}) as root:
            with self.assertRaises(ValueError):
                get_adapter("claude-code").render_folder_rules(root)

    def test_copilot_is_an_extension_point(self):
        with TempRepo(SOURCE) as root:
            with self.assertRaises(AdapterNotImplemented) as ctx:
                get_adapter("copilot").render_rules(root)
            self.assertIn("docs/adapters/copilot.md", str(ctx.exception))

    def test_cli_render_and_check(self):
        with TempRepo(SOURCE) as root:
            code, out, _ = run_cli("render", "--tool", "claude-code", str(root))
            self.assertEqual(code, 0, out)
            code, out, _ = run_cli("render", "--tool", "claude-code", "--check", str(root))
            self.assertEqual(code, 0, out)

    def test_framework_claude_md_is_current(self):
        from aidlc.paths import framework_root
        code, out, _ = run_cli("render", "--tool", "claude-code", "--check", str(framework_root()))
        self.assertEqual(code, 0, out)
