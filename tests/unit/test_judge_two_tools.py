import unittest
from datetime import date
from unittest import mock

import yaml

from aidlc import adapters
from aidlc.adapters import get_adapter
from aidlc.adapters.base import RenderedFile, render_outputs, write_rendered
from aidlc.checks.conftest_check import judge_generated
from aidlc.ci_templates import render_ci
from aidlc.repo import init_repo
from tests.helpers import TempRepo, git


class FakeSecondTool:
    """A second adapter, as Copilot will be: its own rules file, nothing in Claude Code's folders."""
    name = "copilot"
    managed_dirs: tuple[str, ...] = ()

    def render_rules(self, repo):
        return [RenderedFile(".github/copilot-instructions.md", "<!-- Generated by aidlc test -->\nx\n")]

    def render_folder_rules(self, repo):
        return []

    def render_permissions(self, repo):
        return []

    def render_hooks(self, repo):
        return []

    def render_skills(self, repo):
        return []

    def render_agents(self, repo):
        return []


def two_tool_repo(root):
    init_repo(root, "svc", "team", "generic", "purpose", date(2026, 10, 23))
    cfg = root / ".aidlc/config.yaml"
    data = yaml.safe_load(cfg.read_text(encoding="utf-8"))
    data["tools"] = ["claude-code", "copilot"]
    cfg.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    for name in ("copilot", "claude-code"):
        adapter = get_adapter(name)
        problems = write_rendered(root, render_outputs(adapter, root) + render_ci(root), check=False,
                                  managed_dirs=adapter.managed_dirs, owner=name)
        assert problems == [], problems


class JudgeTwoToolsTest(unittest.TestCase):
    def test_the_judge_accepts_a_repository_rendered_for_two_tools(self):
        with mock.patch.dict(adapters._ADAPTERS, {"copilot": FakeSecondTool}), TempRepo() as root:
            two_tool_repo(root)
            git(root, "add", "-A")
            git(root, "commit", "-qm", "render")
            fails = [str(f) for f in judge_generated(root, root) if f.level == "FAIL"]
            self.assertEqual(fails, [])

    def test_another_tools_hand_written_config_still_fails(self):
        with mock.patch.dict(adapters._ADAPTERS, {"copilot": FakeSecondTool}), TempRepo() as root:
            two_tool_repo(root)
            (root / ".cursor/rules").mkdir(parents=True)
            (root / ".cursor/rules/a.mdc").write_text("hand written\n", encoding="utf-8")
            git(root, "add", "-A")
            git(root, "commit", "-qm", "render")
            fails = [str(f) for f in judge_generated(root, root) if f.level == "FAIL"]
            self.assertEqual(len([f for f in fails if ".cursor/rules/a.mdc" in f]), 1, fails)
