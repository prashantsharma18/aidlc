import shutil
import tempfile
import unittest
from pathlib import Path

from aidlc.paths import framework_root
from aidlc.trace import check_links, collect, render_tiers_table, render_traceability
from tests.helpers import run_cli


class TraceTest(unittest.TestCase):
    def test_collect_finds_policies_and_templates(self):
        elements, problems = collect()
        self.assertEqual(problems, [])
        kinds = {e.kind for e in elements}
        self.assertTrue({"policy", "template"} <= kinds)

    def test_traceability_lists_every_chapter(self):
        text = render_traceability(collect()[0])
        for n in range(1, 17):
            self.assertIn(f"| {n} |", text)
        self.assertTrue(text.startswith("<!-- Generated by aidlc trace."))

    def test_tiers_table_has_three_tiers(self):
        text = render_tiers_table()
        self.assertIn("Tier 1", text)
        self.assertIn("Tier 3", text)

    def test_generated_docs_are_current(self):
        code, out, _ = run_cli("trace", "--check")
        self.assertEqual(code, 0, out)

    def test_broken_link_is_reported(self):
        tmp = Path(tempfile.mkdtemp())
        try:
            (tmp / "docs").mkdir()
            (tmp / "docs" / "a.md").write_text(
                "[x](missing.md) [ok](a.md) [web](https://x.y) `[code](nope.md)`\n"
                "```\n[fenced](nope2.md)\n```\n", encoding="utf-8")
            problems = check_links(tmp)
            self.assertEqual(len(problems), 1)
            self.assertIn("missing.md", problems[0])
        finally:
            shutil.rmtree(tmp)

    def test_template_without_guide_is_a_problem(self):
        tmp = Path(tempfile.mkdtemp())
        try:
            shutil.copytree(framework_root() / "core", tmp / "core")
            path = tmp / "core" / "templates" / "intent.md"
            path.write_text(path.read_text(encoding="utf-8").replace('guide: ["5.4", "1.3"]\n', ""),
                            encoding="utf-8")
            _, problems = collect(tmp)
            self.assertTrue(any("intent.md" in p for p in problems), problems)
        finally:
            shutil.rmtree(tmp)
