FIX = Path(__file__).resolve().parents[1] / "fixtures" / "render" / "claude-code"


def scaffolded(profile="node"):
    repo = TempRepo({"package.json": "{}\n"})
    root = repo.__enter__()
    init_repo(root, "svc", "team", profile, "purpose", date(2026, 10, 19))
    return repo, root


class ClaudeSettingsTest(unittest.TestCase):
    def setUp(self):
        self.repo, self.root = scaffolded()

    def tearDown(self):
        self.repo.__exit__(None, None, None)

    def settings(self):
        [f] = get_adapter("claude-code").render_permissions(self.root)
        self.assertEqual(f.path, ".claude/settings.json")
        return json.loads(f.content), f.content

    def test_golden_node_settings(self):
        _, text = self.settings()
        self.assertEqual(text, (FIX / "settings.node.json").read_text(encoding="utf-8"))

    def test_secrets_denied_twice(self):
        s, _ = self.settings()
        deny = s["permissions"]["deny"]
        for rule in ("Read(.env)", "Read(.env.*)", "Read(~/.ssh/**)", "Read(~/.openwiki/**)"):
            self.assertIn(rule, deny)
        for path in ("./.env", "./.env.*", "./**/*.pem", "~/.ssh", "~/.openwiki"):
            self.assertIn(path, s["sandbox"]["filesystem"]["denyRead"])

    def test_sandbox_cannot_fall_back(self):
        s, _ = self.settings()
        self.assertEqual((s["sandbox"]["enabled"], s["sandbox"]["failIfUnavailable"],
                          s["sandbox"]["allowUnsandboxedCommands"]), (True, True, False))

    def test_hooks_block_on_failure(self):
        s, _ = self.settings()
        for event in ("PreToolUse", "PostToolUse"):
            [entry] = s["hooks"][event]
            self.assertEqual(entry["hooks"][0]["onFailure"], "block")
            self.assertIn(".aidlc/hooks/claude_shim.py", entry["hooks"][0]["command"])

    def test_protected_paths_denied_for_edit(self):
        s, _ = self.settings()
        for rule in ("Edit(.aidlc/**)", "Edit(AGENTS.md)", "Edit(.claude/**)", "Edit(~/.aidlc/**)"):
            self.assertIn(rule, s["permissions"]["deny"])

    def test_plugin_isolation_and_memory(self):
        cfg = self.root / ".aidlc/config.yaml"
        cfg.write_text(cfg.read_text().replace("disable_user_plugins: []",
                                               "disable_user_plugins: [spec-pack@local]"))
        s, _ = self.settings()
        self.assertEqual(s["enabledPlugins"], {"spec-pack@local": False})
        self.assertIs(s["autoMemoryEnabled"], False)

    def test_hook_files_rendered_with_marker_and_harness(self):
        files = {f.path: f.content for f in get_adapter("claude-code").render_hooks(self.root)}
        self.assertEqual(set(files), {".aidlc/hooks/guard.py", ".aidlc/hooks/post_check.py",
                                      ".aidlc/hooks/claude_shim.py", ".aidlc/hooks/harness.json"})
        self.assertTrue(files[".aidlc/hooks/guard.py"].splitlines()[1].startswith("# Generated by aidlc"))
        self.assertIn("git push*", json.loads(files[".aidlc/hooks/harness.json"])["shell_deny"])

    def test_cli_render_writes_everything_then_check_is_clean(self):
        code, out, _ = run_cli("render", "--tool", "claude-code", str(self.root))
        self.assertEqual(code, 0, out)
        self.assertTrue(os.access(self.root / ".aidlc/hooks/claude_shim.py", os.R_OK))
        code, out, _ = run_cli("render", "--tool", "claude-code", "--check", str(self.root))
        self.assertEqual(code, 0, out)

    def test_default_scope_path_matches_guard(self):
        guard = load_hook("guard")
        os.environ.pop("AIDLC_SCOPE_FILE", None)
        self.assertEqual(default_scope_path(self.root, "feat/SHIP-1-x"),
                         guard.scope_file(self.root, "feat/SHIP-1-x"))


class SandboxDenyWriteTest(unittest.TestCase):
    def setUp(self):
        self.repo, self.root = scaffolded()
        for rel in ("a/AGENTS.md", "scripts/check.sh"):
            (self.root / rel).parent.mkdir(parents=True, exist_ok=True)
            (self.root / rel).write_text("x\n", encoding="utf-8")
        git(self.root, "add", "a/AGENTS.md", "scripts/check.sh")
        (self.root / "b").mkdir()
        (self.root / "b/AGENTS.md").write_text("untracked\n", encoding="utf-8")

    def tearDown(self):
        self.repo.__exit__(None, None, None)

    def deny_write(self):
        [f] = get_adapter("claude-code").render_permissions(self.root)
        return json.loads(f.content)["sandbox"]["filesystem"]

    def test_literals_and_expanded_tracked_matches(self):
        fs = self.deny_write()
        dw = fs["denyWrite"]
        for path in ("./a/AGENTS.md", "./scripts/check.sh", "./AGENTS.md", "./.aidlc",
                     "~/.aidlc", "./.git/hooks", "./.git/config"):
            self.assertIn(path, dw)
        self.assertNotIn("./.git", dw)
        self.assertEqual([p for p in dw if re.search(r"[*?\[]", p)], [])
        self.assertEqual(len(dw), len(set(dw)))

    def test_untracked_not_listed(self):
        self.assertNotIn("./b/AGENTS.md", self.deny_write()["denyWrite"])

    def test_filesystem_key_order(self):
        self.assertEqual(list(self.deny_write()), ["denyRead", "denyWrite", "allowWrite"])

    def test_not_a_git_repository_is_an_error(self):
        import shutil
        shutil.rmtree(self.root / ".git")
        with self.assertRaises(HarnessError):
            get_adapter("claude-code").render_permissions(self.root)

    def test_git_env_is_ignored(self):
        os.environ["GIT_DIR"] = "/nonexistent"
        try:
            self.assertIn("./a/AGENTS.md", self.deny_write()["denyWrite"])
        finally:
            del os.environ["GIT_DIR"]


class MatcherSyncTest(unittest.TestCase):
    """Final review ruling (final-fixes F1): every tool reaches the pre hook and the guard
    classifies it; the post hook covers modifying tools and background shell output."""

    def test_pre_matcher_matches_every_tool_name(self):
        shim = load_hook("claude_shim")
        pre = re.compile(PRE_MATCHER)
        for name in (*shim.CLASSES, "mcp__x__y", "Teleport", "SomeFutureTool", "TodoWrite", "Task"):
            self.assertTrue(pre.search(name), name)

    def test_read_class_tools_are_allowed_by_the_guard(self):
        shim, guard = load_hook("claude_shim"), load_hook("guard")
        with GuardEnv():
            for name, cls in shim.CLASSES.items():
                if cls == "read":
                    event = shim.to_generic({"tool_name": name, "tool_input": {}, "cwd": "/tmp"}, "pre")
                    self.assertEqual(guard.decide(event)["decision"], "allow", name)

    def test_unknown_tool_asks(self):
        shim, guard = load_hook("claude_shim"), load_hook("guard")
        with GuardEnv():
            event = shim.to_generic({"tool_name": "Teleport", "tool_input": {}, "cwd": "/tmp"}, "pre")
            self.assertEqual((guard.decide(event)["decision"], guard.decide(event)["rule"]),
                             ("ask", "unknown-tool"))

    def test_monitor_is_shell(self):
        shim = load_hook("claude_shim")
        self.assertEqual(shim.CLASSES["Monitor"], "shell")

    def test_post_matcher_is_exactly_the_modifying_set(self):
        shim = load_hook("claude_shim")
        post = re.compile(POST_MATCHER)
        expected = {"Edit", "Write", "MultiEdit", "NotebookEdit", "Bash", "Monitor", "BashOutput"}
        for name in (*shim.CLASSES, "mcp__x__y", "Teleport", "EditX", "XBash", "Read"):
            self.assertEqual(bool(post.search(name)), name in expected, name)


